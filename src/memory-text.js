/**
 * The title and caption for a memory, falling back to whatever the photo already carries.
 * The fallback is what keeps `id` from being load-bearing: rename a photo and the dialog still reads.
 */
export function textFor(memory) {
  const text = memoryText[memory.id];
  return { title: text?.title ?? memory.title, caption: text?.caption ?? memory.caption };
}
